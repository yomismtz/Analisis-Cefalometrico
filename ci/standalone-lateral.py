from pathlib import Path
import re

ROOT = Path('.')
java_dir = ROOT / 'app/src/main/java/com/cefalo/angulos'

# -----------------------------------------------------------------------------
# Identity: this is the dedicated lateral-skull application, not the full app.
# -----------------------------------------------------------------------------
gradle = ROOT / 'app/build.gradle'
g = gradle.read_text(encoding='utf-8')
g = re.sub(r"applicationId\s+'[^']+'", "applicationId 'com.yomceph.cefalometrico'", g, count=1)
g = re.sub(r'versionCode\s+\d+', 'versionCode 33', g, count=1)
g = re.sub(r"versionName\s+'[^']+'", "versionName '1.32'", g, count=1)
gradle.write_text(g, encoding='utf-8')

for path in [ROOT / 'app/src/main/res/values/strings.xml', ROOT / 'app/src/main/res/values-en/strings.xml']:
    s = path.read_text(encoding='utf-8')
    if 'values-en' in str(path):
        replacements = {
            'app_name': 'Yom lateral skull analysis',
            'app_slogan': 'Comprehensive lateral cephalometric analysis',
            'analysis_steiner': 'COMPREHENSIVE CEPHALOMETRIC ANALYSIS',
            'section_lateral': 'LATERAL SKULL RADIOGRAPH',
        }
    else:
        replacements = {
            'app_name': 'Yom análisis de lateral de cráneo',
            'app_slogan': 'Análisis cefalométrico integral',
            'analysis_steiner': 'ANÁLISIS CEFALOMÉTRICO INTEGRAL',
            'section_lateral': 'RADIOGRAFÍA LATERAL DE CRÁNEO',
        }
    for key, value in replacements.items():
        s = re.sub(
            rf'<string name="{re.escape(key)}">.*?</string>',
            f'<string name="{key}">{value}</string>',
            s,
            count=1,
            flags=re.S,
        )
    path.write_text(s, encoding='utf-8')

# -----------------------------------------------------------------------------
