test.write_text(r'''package com.cefalo.angulos;

import static org.junit.Assert.assertTrue;

import org.junit.Test;

public class StandaloneLateralCatalogTest {
    private static boolean hasAngular(String token) {
        for (MeasurementDefinition def : MeasurementCatalog.steiner()) {
            if (def.name.contains(token)) return true;
        }
        return false;
    }

    private static boolean hasLinear(String token) {
        for (LinearMeasurementDefinition def : LinearMeasurementCatalog.cephalometric()) {
            if (def.name.contains(token)) return true;
        }
        return false;
    }

    @Test public void combinesSteinerBjorkRickettsAndMcNamara() {
        assertTrue(hasAngular("SNA"));
        assertTrue(hasAngular("Ángulo de la silla"));
        assertTrue(hasAngular("Ricketts · Profundidad maxilar"));
        assertTrue(hasAngular("Ricketts · Eje facial"));
        assertTrue(hasLinear("Co-A"));
        assertTrue(hasLinear("Co-Gn"));
        assertTrue(hasLinear("vía aérea superior mínima"));
    }
}
''', encoding='utf-8')

