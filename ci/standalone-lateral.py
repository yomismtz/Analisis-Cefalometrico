                "Marque Ba-N y el eje facial Pt-Gn. Pt corresponde al punto pterigoideo/foramen rotundum definido por Ricketts.",
                "Eje facial menor que la referencia: tendencia de crecimiento relativamente más vertical y/o mentón más posterior; interpretar con el resto del patrón.",
